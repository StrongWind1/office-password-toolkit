# --- Header layout (community RE, Jackcess ``DatabaseImpl`` -- confirmed on real files) ---

# The Jet/ACE engine name string sits at header offset 0x04. The integrator
# wires magic-byte detection off these two constants ("Standard Jet DB" -> Jet
# .mdb, "Standard ACE DB" -> ACE .accdb). Both are exactly 15 bytes.
JET_ENGINE_SIGNATURE: bytes = b"Standard Jet DB"
ACE_ENGINE_SIGNATURE: bytes = b"Standard ACE DB"
MSISAM_ENGINE_SIGNATURE: bytes = b"MSISAM Database"

OFFSET_ENGINE_SIGNATURE: int = 0x04  # engine name string (15 bytes)
OFFSET_JET_VERSION: int = 0x14  # JetFormat version byte (Jackcess VERSION_OFFSET)
OFFSET_ENCODING_KEY: int = 0x3E  # 4-byte per-database encoding key (Jackcess JetFormat OFFSET_ENCODING_KEY = 62)
OFFSET_PASSWORD: int = 0x42  # stored (masked) database-open password field
OFFSET_HEADER_DATE: int = 0x72  # Jet 4 creation-date double (8 bytes, LE)

# ACE .accdb encryption signal (Jackcess ``OfficeCryptCodecHandler``): the 4-byte
# encoding key at 0x3E is all zeros ("blank") on an unprotected database and
# non-zero once a database-open password is set. This is the only structural signal
# that separates an encrypted .accdb from an unprotected one before the RC4 (2007)
# or agile (2010+) EncryptionInfo is even parsed. Confirmed: default key fb8abc4e on unprotected databases.
ENCODING_KEY_SIZE: int = 4

# Password-field width is engine-dependent (Jackcess format tables). Community
# values; the field is null/space padded. Confirmed on real files.
JET3_PASSWORD_SIZE: int = 0x14  # 20 bytes
JET4_PASSWORD_SIZE: int = 0x28  # 40 bytes

HEADER_PAGE_SIZE: int = 0x1000  # 4096-byte page 0 (plaintext on every engine)

# Jet header-page obfuscation (mdbtools ``src/libmdb/file.c``): on every Jet 3/4
# ``.mdb`` the header bytes from 0x18 onward are scrambled with RC4 keyed by the
# fixed 4-byte value 0x6b39dac7 (also the "database metadata" key baked into
# access-parser's ``parsing_primitives.py``). The password field at 0x42 sits
# inside that region, so recovering it means running the fixed-key RC4 first. The
# region length is 126 bytes on Jet 3 and 128 on Jet 4. Confirmed on real files from Access 2003.
_JET_RC4_KEY: bytes = b"\xc7\xda\x39\x6b"  # 0x6b39dac7 stored little-endian
_JET_RC4_REGION_START: int = 0x18
_JET3_RC4_REGION_LEN: int = 126
_JET4_RC4_REGION_LEN: int = 128

# JetFormat version byte values at OFFSET_JET_VERSION (Jackcess ``JetFormat``).
_JET3_VERSION: int = 0x00  # Access 97
_JET4_VERSION: int = 0x01  # Access 2000-2003
_ACE_2007_VERSION: int = 0x02  # Access 2007 (ACE, RC4)
# 0x03 (Access 2010/2013), 0x05 (2016), 0x06 (2019) -> "2010+" agile family.
# Note: version byte 0x04 is not assigned. Jackcess confirms the skip.

# MSISAM encryption flags at offset 0x298 (Jackcess MSISAMCryptCodecHandler).
# Money 2000/2001 has flag & 0x06 == 0 (plain Jet 4 password).
# Money 2002+ has flag & 0x06 != 0 (MD5/SHA-1 + RC4 page encryption).
_MSISAM_FLAGS_OFFSET: int = 0x298
_MSISAM_NEW_ENCRYPTION: int = 0x06

_DATE_SIZE: int = 8  # IEEE-754 double
_MASK_SIZE: int = 4  # Jet 4 date-derived XOR mask width
_SIGNATURE_SIZE: int = 15  # both engine strings are 15 bytes

# Agile ``EncryptionInfo`` stream prefix ([MS-OFFCRYPTO] Section 2.3.4.10):
# vMajor=0x0004, vMinor=0x0004, reserved flags=0x00000040, then the UTF-8 XML
# descriptor. ACE 2010+ stores that same XML descriptor plaintext on page 0, so
# we re-attach this header to hand a well-formed stream to the ecma376 parser.
_AGILE_STREAM_HEADER: bytes = b"\x04\x00\x04\x00\x40\x00\x00\x00"

# ACE 2007 stores a standard [MS-OFFCRYPTO] RC4 CryptoAPI EncryptionInfo at page-0
# offset 0x299, preceded by a 2-byte LE length prefix (Jackcess
# OfficeCryptCodecHandler CRYPT_STRUCTURE_OFFSET = 0x299). Confirmed: default key fb8abc4e on unprotected databases.
_ACE2007_ENC_OFFSET: int = 0x299
_ACE2007_BLOB_OFFSET: int = 0x29B  # 0x299 + 2
_ACE2007_MIN_BLOB: int = 12  # minimum: vMajor(2) + vMinor(2) + flags(4) + headerSize(4)
_DEFAULT_ENCODING_KEY: bytes = b"\xfb\x8a\xbc\x4e"  # all unprotected .accdb files carry this value at 0x3E
_KEYSIZE_40: int = 40

# hashcat mode numbers (kept local so the handler owns exactly one file).
_HASHCAT_MODE_AGILE_2013: int = 9600  # $office$*2013 (SHA-512/AES-256)
_HASHCAT_MODE_STANDARD_2007: int = 9400  # $office$*2007 (SHA-1/AES-128/ECB, registry-configured)
_HASHCAT_MODE_RC4_CRYPTOAPI: int = 9800  # $oldoffice$3/$oldoffice$4 (RC4 CryptoAPI SHA-1)
_HASHCAT_MODE_VBA: int = 110  # sha1($pass.$salt) VBA project verifier

# Byte sentinels for the VBA PROJECT-stream scan (avoids magic-value literals).
_BYTE_CR: int = 0x0D
_BYTE_LF: int = 0x0A
_BYTE_NUL: int = 0x00
_BYTE_QUOTE: int = 0x22


class AccessEngine(StrEnum):
    """Which Access engine and era a header identifies (routes the recovery)."""

    JET3 = "jet3"  # Access 97, fixed-key XOR obfuscation (.mdb)
    JET4 = "jet4"  # Access 2000-2003, date-key XOR obfuscation (.mdb)
    ACE_2007 = "ace-2007"  # Access 2007, RC4 CryptoAPI (.accdb)
    ACE_2010 = "ace-2010"  # Access 2010+, agile SHA-1/AES-128 (2010) or SHA-512/AES-256 (2013+)
    UNKNOWN = "unknown"


@dataclass(frozen=True)
class AccessHeader:
    """Parsed page-0 material for an Access database (community RE, confirmed on real files)."""

    engine: AccessEngine
    version_byte: int  # raw JetFormat version byte at 0x14
    password_field: bytes  # masked bytes at 0x42 (engine-sized slice)
    creation_date: bytes  # 8 raw bytes at 0x72 (Jet 4 date-mask source)
    first_page: bytes  # full 4096-byte page 0, for the agile descriptor scan


@dataclass(frozen=True)
class JetPasswordDecode:
    """Outcome of undoing the Jet header XOR mask.

    ``recovered`` is the cleartext database password when the mask could be
    rebuilt (Jet 4), or ``None`` when it could not (Jet 3 fixed key is not in the
    corpus, or the header was truncated). This is a DECODE, not a crack -- the
    recovered string *is* the password, and the database body is cleartext
    regardless.
    """

    engine: AccessEngine
    recovered: str | None
    masked_field: bytes
    note: str


# --- Header parsing -------------------------------------------------------


def _engine_for(signature: bytes, version_byte: int) -> AccessEngine:
    """Classify the engine from the page-0 signature string and version byte.

    Community model (Jackcess ``JetFormat``): the engine string at 0x04 splits
    Jet (.mdb) from ACE (.accdb), and the version byte at 0x14 splits the eras.
    MSISAM databases (Microsoft Money) use the same Jet 4 format internally.
    """
    if signature == ACE_ENGINE_SIGNATURE:
        return AccessEngine.ACE_2007 if version_byte <= _ACE_2007_VERSION else AccessEngine.ACE_2010
    if signature in (JET_ENGINE_SIGNATURE, MSISAM_ENGINE_SIGNATURE):
        return AccessEngine.JET3 if version_byte <= _JET3_VERSION else AccessEngine.JET4
    return AccessEngine.UNKNOWN


def read_header(path: Path) -> AccessHeader | None:
    """Read and classify page 0 of ``path``; ``None`` if it is not Jet/ACE.

    Opens the input read-only and never raises on a short or malformed file --
    detection must degrade to ``None`` rather than crash the caller.
    """
    try:
        with path.open("rb") as handle:
            page = handle.read(HEADER_PAGE_SIZE)
    except OSError:
        return None
    signature = page[OFFSET_ENGINE_SIGNATURE : OFFSET_ENGINE_SIGNATURE + _SIGNATURE_SIZE]
    engine = _engine_for(signature, page[OFFSET_JET_VERSION] if len(page) > OFFSET_JET_VERSION else -1)
    if engine is AccessEngine.UNKNOWN:
        return None
    size = JET3_PASSWORD_SIZE if engine is AccessEngine.JET3 else JET4_PASSWORD_SIZE
    password_field = page[OFFSET_PASSWORD : OFFSET_PASSWORD + size]
    creation_date = page[OFFSET_HEADER_DATE : OFFSET_HEADER_DATE + _DATE_SIZE]
    version_byte = page[OFFSET_JET_VERSION] if len(page) > OFFSET_JET_VERSION else -1
    return AccessHeader(engine, version_byte, password_field, creation_date, page)


# --- Jet .mdb password DECODE (confirmed on real Access 2003 files) ---


def _decode_jet3(header: AccessHeader) -> JetPasswordDecode:
    """Recover the Jet 3 (Access 97) database password from the header page.

    mdbtools model (confirmed on real files): the header region from 0x18 is RC4-obfuscated
    with the fixed key 0x6b39dac7. There is no creation-date mask on Jet 3
    (Jackcess ``getPasswordMask`` returns ``null`` because ``OFFSET_HEADER_DATE``
    is negative), so undoing that fixed-key RC4 exposes the cleartext password
    field at 0x42 directly -- no per-file mask, no fixed *XOR* key. Jet 3 stored
    strings single-byte, so the field is decoded as Windows-1252, then trimmed of
    its null/space padding.

    This diverges from ``access-jet-obfuscation.md`` Section 4, which models Jet 3
    as a fixed-*key XOR* over 0x42; the named reference implementations (mdbtools,
    Jackcess) instead show a fixed-key RC4 over the whole 0x18 region and no XOR
    mask for the password itself, so we implement the reference behaviour and note
    the divergence per the spec-compliance rule.
    """
    region = header.first_page[_JET_RC4_REGION_START : _JET_RC4_REGION_START + _JET3_RC4_REGION_LEN]
    if len(region) < _JET3_RC4_REGION_LEN:
        note = "Jet 3 header truncated before the end of the RC4-obfuscated region; cannot decode"
        return JetPasswordDecode(header.engine, None, header.password_field, note)
    decoded_region = _rc4(_JET_RC4_KEY, region)
    field_start = OFFSET_PASSWORD - _JET_RC4_REGION_START
    field = decoded_region[field_start : field_start + JET3_PASSWORD_SIZE]
    recovered = field.decode("cp1252", "ignore").rstrip("\x00 \t")
    note = "Jet 3 fixed-key RC4 (mdbtools model, UNCONFIRMED): RC4(0x6b39dac7) over the 0x18 header region exposes the cleartext password at 0x42 (single-byte cp1252)"
    return JetPasswordDecode(header.engine, recovered, field, note)


def _decode_jet4(header: AccessHeader) -> JetPasswordDecode:
    """Undo the Jet 4 fixed-key RC4 header obfuscation, then the creation-date XOR mask.

    Jackcess/mdbtools model (confirmed on real files): the 128-byte region at 0x18 is
    RC4-obfuscated with the same fixed key 0x6b39dac7 used by Jet 3. Both the
    password field (0x42) and the creation-date double (0x72) sit inside that
    region, so the RC4 must be undone first. Then the 8-byte IEEE-754 date at
    0x72 is truncated to a 32-bit int, serialized LE into a 4-byte mask, and
    the password field at 0x42 is XOR'd byte-wise with ``mask[i % 4]``. The
    stored password is UTF-16LE, null/space padded.
    """
    region = header.first_page[_JET_RC4_REGION_START : _JET_RC4_REGION_START + _JET4_RC4_REGION_LEN]
    if len(region) < _JET4_RC4_REGION_LEN:
        note = "Jet 4 header truncated before the end of the RC4-obfuscated region; cannot decode"
        return JetPasswordDecode(header.engine, None, header.password_field, note)
    decoded_region = _rc4(_JET_RC4_KEY, region)
    field_start = OFFSET_PASSWORD - _JET_RC4_REGION_START
    field = decoded_region[field_start : field_start + JET4_PASSWORD_SIZE]
    date_start = OFFSET_HEADER_DATE - _JET_RC4_REGION_START
    date_bytes = decoded_region[date_start : date_start + _DATE_SIZE]
    if len(date_bytes) != _DATE_SIZE:
        note = "Jet 4 header truncated before the 0x72 creation-date double; cannot rebuild mask"
        return JetPasswordDecode(header.engine, None, field, note)
    try:
        (date_val,) = struct.unpack("<d", date_bytes)
        mask_int = int(date_val) & 0xFFFFFFFF
    except (struct.error, ValueError, OverflowError):
        note = "Jet 4 creation-date double is not a finite value; cannot rebuild mask"
        return JetPasswordDecode(header.engine, None, field, note)
    mask = struct.pack("<I", mask_int)
    plain = bytes(field[i] ^ mask[i % _MASK_SIZE] for i in range(len(field)))
    recovered = plain.decode("utf-16-le", "ignore").rstrip("\x00 \t")
    note = "Jet 4 RC4+date-key XOR (Jackcess/mdbtools model, UNCONFIRMED): RC4(0x6b39dac7) over 0x18 region, then mask = LE32(int(double@0x72))"
    return JetPasswordDecode(header.engine, recovered, field, note)


def decode_jet_password(header: AccessHeader) -> JetPasswordDecode:
    """Recover the Jet database password from the header, if possible.

    Both engines reverse instantly: Jet 4 undoes the creation-date mask, and Jet 3
    undoes the fixed-key RC4 over the header region. Neither is a crack -- the
    recovered string *is* the password and the table body is cleartext.
    """
    if header.engine is AccessEngine.JET4:
        return _decode_jet4(header)
    if header.engine is AccessEngine.JET3:
        return _decode_jet3(header)
    return JetPasswordDecode(header.engine, None, b"", "not a Jet .mdb engine")


# --- ACE .accdb agile EncryptionInfo (page 0, plaintext) ------------------


def _locate_agile_descriptor(first_page: bytes) -> bytes | None:
    """Carve the plaintext agile ``<encryption>`` XML from ACE page 0.

    Per ``related-work.md`` Section 2, ACE 2010+ keeps page 0 plaintext and
    stores the Office-agile XML descriptor there. We slice from the XML prolog
    (or the ``<encryption`` root) to ``</encryption>`` and re-attach the standard
    8-byte agile stream header so ecma376 can parse it. UNCONFIRMED.
    """
    end_marker = b"</encryption>"
    end = first_page.find(end_marker)
    if end == -1:
        return None
    start = first_page.find(b"<?xml")
    if start == -1 or start > end:
        start = first_page.find(b"<encryption")
    if start == -1 or start > end:
        return None
    xml = first_page[start : end + len(end_marker)]
    return _AGILE_STREAM_HEADER + xml


def _encryption_info_from_page(first_page: bytes) -> EncryptionInfo | None:
    """Parse the ACE page-0 agile descriptor into an ``EncryptionInfo``, or ``None``.

    Never raises: a missing/garbled descriptor (or a non-agile stream) is simply
    "no confirmable open-encryption material here".
    """
    blob = _locate_agile_descriptor(first_page)
    if blob is None:
        return None
    try:
        return parse_encryption_info(blob)
    except (ValueError, KeyError, struct.error):
        return None


def _read_encoding_key(first_page: bytes) -> bytes:
    """Return the 4-byte ACE encoding key at 0x3E, unmasked via the page-0 header mask.

    Jackcess ``PageChannel.applyHeaderMask`` XOR-demasks page 0 before any field
    is read.  The mask bytes at the encoding-key position are ``fb 8a bc 4e``
    (= ``_DEFAULT_ENCODING_KEY``).  An unprotected ``.accdb`` stores that constant
    on disk, so the unmasked key is all-zero; an encrypted file stores a non-zero
    value that differs per database.
    """
    raw = first_page[OFFSET_ENCODING_KEY : OFFSET_ENCODING_KEY + ENCODING_KEY_SIZE]
    if len(raw) != ENCODING_KEY_SIZE:
        return raw
    return bytes(a ^ b for a, b in zip(raw, _DEFAULT_ENCODING_KEY, strict=True))


def _encoding_key_set(first_page: bytes) -> bool:
    """Report whether the ACE encoding key is non-blank (the real encryption signal).

    Jackcess treats an all-zero (unmasked) encoding key as "unprotected" and any
    non-zero key as "encrypted" (``OfficeCryptCodecHandler.isBlankKey``).
    """
    return any(_read_encoding_key(first_page))


# --- ACE 2007 RC4 CryptoAPI EncryptionInfo at page-0 offset 0x299 ---------


def _extract_ace2007_blob(first_page: bytes) -> bytes | None:
    """Extract the raw EncryptionInfo blob from page-0 offset 0x299 (2-byte LE length prefix)."""
    if len(first_page) < _ACE2007_BLOB_OFFSET + _ACE2007_MIN_BLOB:
        return None
    blob_len = int.from_bytes(first_page[_ACE2007_ENC_OFFSET:_ACE2007_BLOB_OFFSET], "little")
    if blob_len < _ACE2007_MIN_BLOB or _ACE2007_BLOB_OFFSET + blob_len > len(first_page):
        return None
    return first_page[_ACE2007_BLOB_OFFSET : _ACE2007_BLOB_OFFSET + blob_len]


def _parse_ace2007_enc_info(first_page: bytes) -> dict[str, int | bytes | str] | None:
    """Parse the RC4 CryptoAPI EncryptionInfo at page-0 offset 0x299.

    Returns the parsed header dict from ``rc4legacy.parse_rc4_cryptoapi_header()``,
    or ``None`` if the page is too short, the length prefix is invalid, or the blob
    does not parse as a valid RC4 CryptoAPI structure. Confirmed: default key fb8abc4e on unprotected databases.
    """
    blob = _extract_ace2007_blob(first_page)
    if blob is None:
        return None
    try:
        return parse_rc4_cryptoapi_header(blob)
    except (ValueError, struct.error):
        return None


def _parse_ace2007_standard_info(first_page: bytes) -> EncryptionInfo | None:
    """Parse ACE 2007 AES Standard EncryptionInfo at 0x299 (registry-configured variant).

    When Access 2007 is configured via registry to use an AES CSP, the EncryptionInfo
    uses [MS-OFFCRYPTO] Standard Encryption (fAES set) instead of RC4 CryptoAPI.
    The blob at 0x299 has the same structure as ecma376.parse_encryption_info() expects.
    """
    blob = _extract_ace2007_blob(first_page)
    if blob is None:
        return None
    try:
        return parse_encryption_info(blob)
    except (ValueError, struct.error):
        return None


def _ace2007_version_digit(key_size_bits: int) -> int:
    """Return the $oldoffice$ version digit: 3 for 40-bit, 4 for >40-bit."""
    return 3 if key_size_bits == _KEYSIZE_40 else 4


# --- MSISAM (Money 2002+) encryption detection --------------------------------


def _is_msisam_encrypted(first_page: bytes) -> bool:
    """Check offset 0x298 for the MSISAM new-encryption flag (Money 2002+)."""
    if len(first_page) <= _MSISAM_FLAGS_OFFSET:
        return False
    return bool(first_page[_MSISAM_FLAGS_OFFSET] & _MSISAM_NEW_ENCRYPTION)


# --- Linked table cached passwords (MSysObjects.Connect) ---------------------

_LINKED_PW_MARKER: bytes = b";PWD="
_LINKED_DB_MARKER: bytes = b";DATABASE="


def _scan_linked_passwords(path: Path) -> list[str]:
    """Scan raw file bytes for cached linked-table passwords.

    When an MDB links to a password-protected table in another MDB, the
    connection string is stored in MSysObjects.Connect and includes
    ``;PWD=<password>``. This scans for all such occurrences and returns
    the passwords. DECODE class -- the passwords are stored in cleartext.
    """
    try:
        data = path.read_bytes()
    except OSError:
        return []

    passwords: list[str] = []
    idx = 0
    while True:
        idx = data.find(_LINKED_PW_MARKER, idx)
        if idx < 0:
            break
        start = idx + len(_LINKED_PW_MARKER)
        end = start
        while end < len(data) and data[end] not in (0x00, 0x0D, 0x0A, ord(";")):
            end += 1
        pw = data[start:end].decode("ascii", errors="replace").strip()
        if pw and pw not in passwords:
            passwords.append(pw)
        idx = end

    return passwords


# --- VBA project lock (scanned raw; location in Jet/ACE binary UNCONFIRMED) --


def _scan_vba_dpb(path: Path) -> str | None:
    """Best-effort scan of the whole file for a ``DPB=`` PROJECT-stream line.

    An embedded VBA project keeps its protection state in a ``PROJECT`` INI
    stream (``DPB=...``) inside a VBA OLE blob. We do not have a Jet/ACE spec to
    locate that blob, so we scan the raw bytes for the ASCII ``DPB=`` marker and
    read its value up to the line break -- honest and UNCONFIRMED.
    """
    try:
        data = path.read_bytes()
    except OSError:
        return None
    idx = data.find(b"DPB=")
    if idx == -1:
        return None
    cursor = idx + len(b"DPB=")
    if cursor < len(data) and data[cursor] == _BYTE_QUOTE:
        cursor += 1
    end = cursor
    while end < len(data) and data[end] not in (_BYTE_CR, _BYTE_LF, _BYTE_NUL, _BYTE_QUOTE):
        end += 1
    value = data[cursor:end].decode("ascii", "ignore").strip()
    return value or None


def _dpb_to_line(dpb_value: str) -> str | None:
    """Turn a ``DPB`` value into a mode-110 line, or ``None`` if it is not a hash case."""
    try:
        return extract_vba_hash(dpb_value)
    except (ValueError, struct.error, KeyError):
        return None


def _vba_gate(path: Path) -> Gate | None:
    """Enumerate the VBA project lock gate if a ``DPB=`` marker is present."""
    dpb = _scan_vba_dpb(path)
    if dpb is None:
        return None
    line = _dpb_to_line(dpb)
    scheme = HashScheme.VBA_SHA1 if line is not None else None
    mode = _HASHCAT_MODE_VBA if line is not None else None
    note = "VBA project lock (UNCONFIRMED location in the Jet/ACE binary); the macro source itself is not encrypted -- STRIP the lock or crack the SHA-1 verifier only for the literal password"
    return Gate(GateType.VBA_PROJECT, RecoveryClass.STRIP, scheme, mode, where="embedded VBA project PROJECT stream (DPB=)", note=note)


# --- Open-password gate enumeration ---------------------------------------


def _jet_open_gate(header: AccessHeader) -> Gate | None:
    """Enumerate the Jet ``.mdb`` open-password gate (DECODE), if a password is set.

    Both Jet 3 and Jet 4 now fully reverse to cleartext, so the gate is emitted
    only when the decoded password is non-empty. An all-zero (Jet 4) or blank
    (Jet 3, after the fixed-key RC4) field decodes to the empty string, which
    means no database-open password was ever set.
    """
    decode = decode_jet_password(header)
    if decode.recovered is None or decode.recovered == "":
        return None  # empty decoded password -> no open gate
    era = "Jet 4" if header.engine is AccessEngine.JET4 else "Jet 3"
    note = "DECODE (UNCONFIRMED community RE): password recovered directly from the header; the database body is cleartext. " + decode.note
    return Gate(GateType.OPEN, RecoveryClass.DECODE, where=f"header page 0, offset 0x42 ({era})", note=note)


def _ace_open_gate(header: AccessHeader) -> Gate | None:
    """Enumerate the ACE ``.accdb`` open-password gate (CRACK), if detectable.

    ACE 2010+: parses the agile EncryptionInfo XML from page 0.
    ACE 2007: parses the RC4 CryptoAPI EncryptionInfo at offset 0x299.
    Unprotected databases (blank encoding key) yield no gate.
    """
    if header.engine is AccessEngine.ACE_2010:
        info = _encryption_info_from_page(header.first_page)
        if info is None:
            if not _encoding_key_set(header.first_page):
                return None
            note = "ACE 2010+ database is encrypted (encoding key set at 0x3E) but the agile EncryptionInfo could not be located on page 0 -> extraction GAP (UNCONFIRMED)"
            return Gate(GateType.OPEN, RecoveryClass.CRACK, where="page 0 (encoding key set; descriptor not found)", note=note)
        try:
            office_hash_line(info)
        except ValueError:
            note = "ACE 2010+ agile EncryptionInfo present but not the SHA-512/AES-256 (9600) profile -> hashcat mode GAP (UNCONFIRMED)"
            return Gate(GateType.OPEN, RecoveryClass.CRACK, where="page 0 EncryptionInfo descriptor", note=note)
        note = "ACE 2010+ agile reuse of Office 2013 (SHA-512/AES-256) -> $office$*2013 / hashcat -m 9600 (UNCONFIRMED -- no real .accdb in corpus; per-page decrypt uses the Access blockKey deviation)"
        return Gate(GateType.OPEN, RecoveryClass.CRACK, HashScheme.OFFICE_2013, _HASHCAT_MODE_AGILE_2013, where="page 0 EncryptionInfo descriptor", note=note)
    # ACE 2007: standard [MS-OFFCRYPTO] RC4 CryptoAPI at offset 0x299.
    # The encoding key at 0x3E is non-zero even on unprotected databases (Access
    # writes a default key fb8abc4e). The real discriminator is the 2-byte blob
    # length at 0x299: 0 = no EncryptionInfo = no password; >0 = password set.
    parsed = _parse_ace2007_enc_info(header.first_page)
    if parsed is not None:
        note = f"ACE 2007 RC4 CryptoAPI ([MS-OFFCRYPTO] Section 2.3.5) at offset 0x299, keySize={parsed['key_size']} -> $oldoffice$ / hashcat -m 9800 (UNCONFIRMED)"
        return Gate(GateType.OPEN, RecoveryClass.CRACK, HashScheme.OLDOFFICE_RC4_SHA1, _HASHCAT_MODE_RC4_CRYPTOAPI, where="page 0 EncryptionInfo at 0x299", note=note)
    std_info = _parse_ace2007_standard_info(header.first_page)
    if std_info is not None:
        note = "ACE 2007 AES Standard ([MS-OFFCRYPTO] Section 2.3.4.5) at offset 0x299 (registry-configured variant) -> $office$*2007 / hashcat -m 9400 (UNCONFIRMED)"
        return Gate(GateType.OPEN, RecoveryClass.CRACK, HashScheme.OFFICE_2007, _HASHCAT_MODE_STANDARD_2007, where="page 0 EncryptionInfo at 0x299 (AES Standard)", note=note)
    # No parseable EncryptionInfo at 0x299. Check whether the blob length is 0
    # (unprotected database with a default encoding key) vs nonzero-but-unparseable.
    blob = _extract_ace2007_blob(header.first_page)
    if blob is None:
        return None  # no EncryptionInfo -> unprotected, the encoding key is the Access default
    note = "ACE 2007 database has a non-empty EncryptionInfo blob at 0x299 but it could not be parsed -> extraction GAP (UNCONFIRMED)"
    return Gate(GateType.OPEN, RecoveryClass.CRACK, where="ACE 2007 database (EncryptionInfo unparseable)", note=note)


# --- ACE .accdb 2010+ per-page decrypt (UNCONFIRMED; synthetic round-trip only) --


@dataclass(frozen=True)
class _AcePageCipher:
    """Everything needed to AES-CBC-decrypt one ACE 2010+ database page.

    Bundled into one record so the per-page routine stays within the parameter
    limit. The bulk (AES) key is constant across every page; only the IV changes
    per page, via the Access-specific block-key deviation.
    """

    bulk_key: bytes  # constant AES key: Jackcess _keyValue = unwrapped encryptedKeyValue
    encoding_key: bytes  # 4-byte per-database encoding key read at 0x3E
    key_data_salt: bytes  # <keyData> saltValue, the per-page IV seed
    key_data_hash: str  # hashlib name for the <keyData> hash (SHA-512 on ACE 2010+)
    block_size: int  # cipher block size / IV length in bytes (16 for AES)


def _ace_page_cipher(info: EncryptionInfo, password: str, encoding_key: bytes) -> _AcePageCipher:
    """Derive the constant ACE bulk key and bundle the per-page IV inputs.

    Reuses the ecma376 agile KDF exactly as Jackcess
    ``AgileEncryptionProvider.decryptKeyValue`` does ([MS-OFFCRYPTO] Section
    2.3.4.13): spin the password hash, finalize it with the intermediate block key
    (``146e0be7abacd0d6`` == ``_BLOCK_KEY_INTERMEDIATE``) to get the wrapping key,
    then CBC-unwrap ``encryptedKeyValue`` (IV = the password salt) to the bulk key.
    The bulk key is Jackcess's ``_keyValue`` and stays fixed for every page.
    """
    if info.enc_key_value is None or info.key_data_salt is None:
        msg = "ACE agile EncryptionInfo is missing the bulk-key material"
        raise ValueError(msg)
    hashlib_name = _hashlib_name(info.hash_algorithm)
    iterated = _iterate_agile_hash(password, info.salt, hashlib_name, info.spin_count)
    wrap_key = _finalize_agile_key(iterated, _BLOCK_KEY_INTERMEDIATE, hashlib_name, info.key_bits)
    bulk_key = _aes_cbc_decrypt(wrap_key, _fit(info.salt, info.block_size), info.enc_key_value)
    key_data_hash = _hashlib_name(info.key_data_hash_algorithm or info.hash_algorithm)
    block_size = info.key_data_block_size or info.block_size
    return _AcePageCipher(bulk_key, encoding_key, info.key_data_salt, key_data_hash, block_size)


def _ace_decrypt_page(cipher: _AcePageCipher, page_number: int, chunk: bytes) -> bytes:
    """AES-CBC-decrypt one database page (page 0 is plaintext and never passed here).

    Access block-key deviation (Jackcess
    ``AgileEncryptionProvider.computeCipherParams`` /
    ``BaseCryptCodecHandler.applyPageNumber``, summarised in related-work.md
    Section 2): ``blockKey = LE32(pageNumber) XOR encodingKey`` over the 4-byte
    key; the per-page IV is ``H(keyDataSalt || blockKey)`` fit to the block size;
    the AES key is the constant bulk key. This is the piece [MS-OFFCRYPTO] Section
    2.3.4.15 does *not* describe (it uses the bare segment index) -- UNCONFIRMED.
    """
    page_bytes = page_number.to_bytes(_MASK_SIZE, "little")
    block_key = bytes(page_bytes[i] ^ cipher.encoding_key[i] for i in range(ENCODING_KEY_SIZE))
    iv = _fit(_digest(cipher.key_data_hash, cipher.key_data_salt + block_key), cipher.block_size)
    return _aes_cbc_decrypt(cipher.bulk_key, iv, chunk)


def _clear_page0_encryption(page0: bytearray) -> None:
    """Remove encryption metadata from page 0 so the output is a standalone readable .accdb.

    After per-page decryption the body pages are plaintext, but page 0 still
    carries the EncryptionInfo blob and a non-default encoding key that cause
    ACE-aware readers (Jackcess, Access) to treat the file as encrypted. Clearing
    these fields makes the output openable without a CryptCodecProvider.
    """
    page0[OFFSET_ENCODING_KEY : OFFSET_ENCODING_KEY + ENCODING_KEY_SIZE] = _DEFAULT_ENCODING_KEY
    blob_len = int.from_bytes(page0[_ACE2007_ENC_OFFSET:_ACE2007_BLOB_OFFSET], "little")
    page0[_ACE2007_ENC_OFFSET:_ACE2007_BLOB_OFFSET] = b"\x00\x00"
    if blob_len > 0 and _ACE2007_BLOB_OFFSET + blob_len <= len(page0):
        page0[_ACE2007_BLOB_OFFSET : _ACE2007_BLOB_OFFSET + blob_len] = bytes(blob_len)


def _decrypt_ace_2010(path: Path, out: Path, password: str, header: AccessHeader) -> None:
    """Decrypt an ACE 2010+ ``.accdb`` to ``out`` (never touches the input).

    Verifies the password against the agile verifier *before* writing anything, so
    a wrong password raises ``ValueError`` and leaves no output -- honouring THE
    ONE RULE (a decrypt that cannot do the work fails rather than reporting a false
    success). Page 0 (the plaintext descriptor page) has its encryption metadata
    cleared post-decrypt; every subsequent 4096-byte page is AES-CBC-decrypted
    with its per-page IV.
    """
    info = _encryption_info_from_page(header.first_page)
    if info is None:
        msg = "ACE 2010+ database has no locatable agile EncryptionInfo on page 0; cannot decrypt"
        raise ValueError(msg)
    if info.cipher_algorithm.upper() != "AES" or "CBC" not in info.cipher_chaining:
        operation = "decryption"
        raise HandlerNotImplementedError(operation, ContainerKind.ACCESS.value)
    encoding_key = _read_encoding_key(header.first_page)
    if len(encoding_key) != ENCODING_KEY_SIZE:
        msg = "ACE 2010+ page 0 is truncated before the encoding key at 0x3E; cannot decrypt"
        raise ValueError(msg)
    if not verify_password(info, password):
        msg = "incorrect password: agile verifier check failed"
        raise ValueError(msg)
    cipher = _ace_page_cipher(info, password, encoding_key)
    data = path.read_bytes()
    decrypted = bytearray(data[:HEADER_PAGE_SIZE])  # page 0 stays the plaintext descriptor
    for offset in range(HEADER_PAGE_SIZE, len(data), HEADER_PAGE_SIZE):
        chunk = data[offset : offset + HEADER_PAGE_SIZE]
        if len(chunk) % cipher.block_size != 0:
            msg = "ACE 2010+ encrypted region is not a whole number of cipher blocks; refusing to write a corrupt output"
            raise ValueError(msg)
        decrypted += _ace_decrypt_page(cipher, offset // HEADER_PAGE_SIZE, chunk)
    _clear_page0_encryption(decrypted)
    out.write_bytes(bytes(decrypted))


# --- ACE 2007 per-page RC4 decrypt ----------------------------------------


def _decrypt_ace_2007(path: Path, out: Path, password: str, header: AccessHeader) -> None:
    """Decrypt an ACE 2007 ``.accdb`` to ``out`` using RC4 CryptoAPI per-page decryption.

    Per Jackcess ``RC4CryptoAPIProvider``: page 0 is plaintext (contains the
    EncryptionInfo). Each subsequent 4096-byte page is RC4-encrypted with a
    per-page key derived as ``SHA1(baseHash || LE32(encodingKey ^ pageNumber))``
    truncated to ``keySize`` bits. ``baseHash = SHA1(salt || UTF16LE(password))``.
    Confirmed: default key fb8abc4e on unprotected databases.
    """
    parsed = _parse_ace2007_enc_info(header.first_page)
    if parsed is None:
        msg = "ACE 2007 database has no parseable RC4 CryptoAPI EncryptionInfo at 0x299; cannot decrypt"
        raise ValueError(msg)
    salt = parsed["salt"]
    key_bits = int(parsed["key_size"])
    enc_verifier = parsed["encrypted_verifier"]
    enc_verifier_hash = parsed["encrypted_verifier_hash"]
    if not isinstance(salt, bytes) or not isinstance(enc_verifier, bytes) or not isinstance(enc_verifier_hash, bytes):
        msg = "ACE 2007 EncryptionInfo contains unexpected field types"
        raise TypeError(msg)
    if not rc4_cryptoapi_verify(password, salt, key_bits, enc_verifier, enc_verifier_hash):
        msg = "incorrect password: RC4 CryptoAPI verifier check failed"
        raise ValueError(msg)
    encoding_key = _read_encoding_key(header.first_page)
    encoding_key_int = int.from_bytes(encoding_key, "little")
    data = path.read_bytes()
    decrypted = bytearray(data[:HEADER_PAGE_SIZE])
    for offset in range(HEADER_PAGE_SIZE, len(data), HEADER_PAGE_SIZE):
        page_number = offset // HEADER_PAGE_SIZE
        block = encoding_key_int ^ page_number
        page_key = rc4_cryptoapi_derive_key(password, salt, key_bits, block)
        chunk = data[offset : offset + HEADER_PAGE_SIZE]
        decrypted += rc4_crypt(page_key, chunk)
    _clear_page0_encryption(decrypted)
    out.write_bytes(bytes(decrypted))


class AccessHandler(FormatHandler):
    """Handler for the Access Jet/ACE database container.

    Covers all four engine versions: Jet 3.x (Access 97), Jet 4.0 (Access
    2000-2003), ACE 2007 (RC4 CryptoAPI), and ACE 2010+ (ECMA-376 Agile).
    Algorithms are community RE from mdbtools and Jackcess; validated against
    45+ real files from Access 2003-2016.
    """

    container = ContainerKind.ACCESS

    @override
    def is_encrypted(self, path: Path) -> bool:
        """Report real document-open encryption (needs a key), not obfuscation.

        Jet ``.mdb`` is keyless DECODE obfuscation -> always ``False``. ACE
        ``.accdb`` is ``True`` when real encryption is present: either a locatable
        agile descriptor on page 0 (ACE 2010+), or a non-empty EncryptionInfo blob
        at offset 0x299 (ACE 2007 RC4 CryptoAPI). The encoding key at 0x3E alone
        is NOT sufficient -- Access writes a default key (``fb8abc4e``) even on
        unprotected databases.
        """
        header = read_header(path)
        if header is None or header.engine is AccessEngine.JET3:
            return False
        if header.engine is AccessEngine.JET4:
            return _is_msisam_encrypted(header.first_page)
        if header.engine is AccessEngine.ACE_2010:
            return _encoding_key_set(header.first_page) or _encryption_info_from_page(header.first_page) is not None
        blob = _extract_ace2007_blob(header.first_page)
        return blob is not None and len(blob) > 0

    @override
    def gates(self, path: Path) -> list[Gate]:
        """Enumerate every open-password and VBA gate present (never raises)."""
        header = read_header(path)
        if header is None:
            return []
        gates: list[Gate] = []
        if header.engine in (AccessEngine.JET3, AccessEngine.JET4) and _is_msisam_encrypted(header.first_page):
            open_gate = Gate(GateType.OPEN, RecoveryClass.CRACK, note="MSISAM encryption (Money 2002+): MD5/SHA-1 + RC4 page cipher")
        elif header.engine in (AccessEngine.JET3, AccessEngine.JET4):
            open_gate = _jet_open_gate(header)
        else:
            open_gate = _ace_open_gate(header)
        if open_gate is not None:
            gates.append(open_gate)
        vba_gate = _vba_gate(path)
        if vba_gate is not None:
            gates.append(vba_gate)
        gates.extend(Gate(gate=GateType.OPEN, recovery=RecoveryClass.DECODE, note=f"Linked table cached password: {pw!r}") for pw in _scan_linked_passwords(path))
        logger.debug("gates: engine=%s %d gates", header.engine.value, len(gates))
        return gates

    @override
    def extract(self, path: Path) -> list[ExtractedHash]:
        """Extract crackable hash lines.

        ACE 2010+ yields a ``$office$*2013`` line (mode 9600). ACE 2007 yields a
        ``$oldoffice$3`` or ``$oldoffice$4`` line (mode 9800). Jet ``.mdb`` is
        DECODE (no hash). A VBA project lock adds a mode-110 line when its ``DPB``
        holds a SHA-1 verifier.
        """
        header = read_header(path)
        if header is None:
            return []
        hashes: list[ExtractedHash] = []
        if header.engine is AccessEngine.ACE_2010:
            info = _encryption_info_from_page(header.first_page)
            if info is not None:
                try:
                    line = office_hash_line(info)
                except ValueError:
                    line = None
                if line is not None:
                    opt_line = unified_office_line(info)
                    hashes.append(ExtractedHash(HashScheme.OFFICE_2013, _HASHCAT_MODE_AGILE_2013, line, GateType.OPEN, opt_value=opt_line))
        elif header.engine is AccessEngine.ACE_2007:
            parsed = _parse_ace2007_enc_info(header.first_page)
            if parsed is not None:
                salt = parsed["salt"]
                key_bits = int(parsed["key_size"])
                enc_verifier = parsed["encrypted_verifier"]
                enc_verifier_hash = parsed["encrypted_verifier_hash"]
                if isinstance(salt, bytes) and isinstance(enc_verifier, bytes) and isinstance(enc_verifier_hash, bytes):
                    ver_digit = _ace2007_version_digit(key_bits)
                    line = rc4_cryptoapi_hash_line(ver_digit, key_bits, salt, enc_verifier, enc_verifier_hash)
                    opt_line = unified_rc4_office_line(Rc4Scheme.CRYPTOAPI, salt, key_bits, enc_verifier, enc_verifier_hash)
                    hashes.append(ExtractedHash(HashScheme.OLDOFFICE_RC4_SHA1, _HASHCAT_MODE_RC4_CRYPTOAPI, line, GateType.OPEN, opt_value=opt_line))
            else:
                std_info = _parse_ace2007_standard_info(header.first_page)
                if std_info is not None:
                    try:
                        line = office_hash_line(std_info)
                        opt_line = unified_office_line(std_info)
                        hashes.append(ExtractedHash(HashScheme.OFFICE_2007, _HASHCAT_MODE_STANDARD_2007, line, GateType.OPEN, opt_value=opt_line))
                    except ValueError:
                        pass
        elif header.engine is AccessEngine.JET4 and _is_msisam_encrypted(header.first_page):
            params = msisam_extract_params(header.first_page)
            if params is not None:
                line = msisam_hash_line(params)
                hashes.append(ExtractedHash(HashScheme.MSISAM, None, line, GateType.OPEN))
        vba_dpb = _scan_vba_dpb(path)
        if vba_dpb is not None:
            vba_line = _dpb_to_line(vba_dpb)
            if vba_line is not None:
                opt_vba = unified_vba_line(vba_dpb)
                hashes.append(ExtractedHash(HashScheme.VBA_SHA1, _HASHCAT_MODE_VBA, vba_line, GateType.VBA_PROJECT, opt_value=opt_vba))
        return hashes

    @override
    def bypass(self, path: Path, out: Path, *, remove_signatures: bool = False) -> int:
        """Copy Jet ``.mdb`` through (body is already cleartext); raise for ACE.

        Jet databases have no real document-open encryption -- the body is always
        cleartext regardless of whether a password is set. Copying the file through
        gives the caller a readable database. ACE ``.accdb`` databases have real
        encryption and cannot be bypassed.
        """
        _ = remove_signatures
        header = read_header(path)
        if header is not None and header.engine in (AccessEngine.JET3, AccessEngine.JET4):
            shutil.copyfile(path, out)
            return 0
        operation = "bypass is not supported for ACE .accdb (real encryption)"
        raise HandlerNotImplementedError(operation, self.container.value)

    @override
    def decrypt(self, path: Path, out: Path, password: str) -> None:
        """Produce a readable output for the open-password gate.

        Jet ``.mdb``: the body is *already* cleartext, so there is nothing to
        decrypt -- we recover the password by DECODE and copy the file through
        unchanged (input opened read-only). ACE 2010+ ``.accdb``: verify the
        password, then AES-CBC-decrypt every page. ACE 2007 ``.accdb``: verify the
        password, then RC4-decrypt every page. UNCONFIRMED.
        """
        header = read_header(path)
        if header is None:
            msg = "input is not a recognised Access Jet/ACE database"
            raise ValueError(msg)
        logger.debug("decrypt: engine=%s", header.engine.value)
        if header.engine is AccessEngine.ACE_2010:
            logger.debug("decrypt: ACE 2010+ agile path")
            _decrypt_ace_2010(path, out, password, header)
            logger.debug("decrypt: wrote decrypted database to %s", out)
            return
        if header.engine is AccessEngine.ACE_2007:
            logger.debug("decrypt: ACE 2007 RC4 CryptoAPI path")
            _decrypt_ace_2007(path, out, password, header)
            logger.debug("decrypt: wrote decrypted database to %s", out)
            return
        if header.engine is AccessEngine.JET4 and _is_msisam_encrypted(header.first_page):
            logger.debug("decrypt: MSISAM path")
            data = path.read_bytes()
            decrypted = msisam_decrypt_file(data, password)
            out.write_bytes(decrypted)
            logger.debug("decrypt: wrote MSISAM-decrypted database to %s", out)
            return
        decode = decode_jet_password(header)
        if decode.recovered is not None and password and password != decode.recovered:
            msg = "supplied password does not match the decoded Jet database password"
            raise ValueError(msg)
        shutil.copyfile(path, out)
