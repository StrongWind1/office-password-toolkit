"""Access handler -- ``.mdb`` / ``.accdb`` databases.

Access databases are proprietary *paged* files, not Office containers: there is
no OLE/CFB, no OPC/ZIP, no ODF-ZIP. ``.mdb`` is the Jet engine (Access 97-2003)
and ``.accdb`` is the ACE engine (Access 2007+).

The byte offsets and algorithms are community reverse-engineering (mdbtools /
Jackcess / jackcess-encrypt). There is no ``[MS-ACCESS]`` or ``[MS-MDB]`` spec
published by Microsoft. The Jackcess pure-Java library
(github.com/jahlborn/jackcess) is the most complete open-source reference for
the Access binary format; its companion ``jackcess-encrypt`` implements all known
encryption dispatch paths.

Validated against 45+ real files generated by Access 2003 (XP), 2007, 2010,
2013, and 2016 via COM automation and RDP GUI interaction on lab VMs. Passwords
verified byte-for-byte on Jet 3.x, Jet 4.0, ACE RC4 CryptoAPI, and ACE Agile.

Gate mapping:

* Jet ``.mdb`` open password -> **DECODE**. Jet 3 (version byte 0x00) undoes the
  fixed-key RC4 over 126 bytes at 0x18 (key ``0x6b39dac7``); Jet 4 (version byte
  0x01) undoes the same RC4 over 128 bytes, then a creation-date XOR mask. Both
  recover the cleartext directly; the body is cleartext. CONFIRMED on real files.
* ACE ``.accdb`` 2010+ open password -> **CRACK**, agile encryption. Office 2010
  uses SHA-1/AES-128 (hashcat 9500); Office 2013+ uses SHA-512/AES-256 (hashcat
  9600). ``decrypt`` reverses the per-page AES-CBC with the Access-specific
  ``blockKey`` deviation (``encodingKey XOR pageNumber``). CONFIRMED on real files.
* ACE ``.accdb`` 2007 open password -> **CRACK**, standard [MS-OFFCRYPTO] RC4
  CryptoAPI encryption (Section 2.3.5). The ``EncryptionInfo`` blob is stored at
  page-0 offset 0x299 with a 2-byte LE length prefix. Default is AlgID=0x6801
  (RC4), KeySize=40, CSP="Microsoft Base Cryptographic Provider v1.0". Emitted
  as ``$oldoffice$3`` / ``$oldoffice$4`` (hashcat 9800). CONFIRMED on real files.
  A theoretical AES Standard variant (fAES flag, hashcat 9400) is handled but has
  not been observed in any real Access installation -- registry override tested on
  Office 2007 and 2013, both still produce their native format. Jackcess carries
  the code path; no known third-party tool or Access build produces it. Treated
  as THEORETICAL and not expected to close without a custom Jet engine build.
* Unprotected ``.accdb`` files have a default encoding key (``fb8abc4e``) at 0x3E
  even without a password; the real encryption indicator is the blob length at
  0x299 (0 = unprotected, >0 = EncryptionInfo present). CONFIRMED by RE.
* Both engines can carry a lockable **VBA project** (STRIP / mode 110).
* ``.mde`` / ``.accde`` are compiled databases with VBA source stripped; they use
  the same encryption as their parent format.
* Jet User-Level Security (``.mdw`` workgroup files) -> **DECODE**. The per-user
  password in ``MSysAccounts.Password`` is 3DES-EDE2-ECB with hardcoded keys
  ``kjhggaut`` / ``nitremvk``, operating on 8-byte UTF-16LE blocks. Decoded by
  ``office_password_toolkit.crypto.uls``. CONFIRMED on 19 test vectors from lab
  VMs; keys reverse-engineered from DES S-boxes in ``msjet40.dll``.
"""

